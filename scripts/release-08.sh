#!/bin/sh
# Cycle 08 release: copies the reproduced ISO into release/ with SHA256SUMS (kernel, initramfs, SquashFS base, ISO),
# runs tests/gate-08.sh against release/cua-agentos.iso, and on a 100/100 pass writes docs/grading-report.md from that
# run's serial telemetry (copied into release/ too). Needs scripts/build-iso-07.sh first.
set -eu
ROOT=$(cd "$(dirname "$0")/.." && pwd)
D=$ROOT/build/iso
R=$ROOT/release
REPORT=$ROOT/docs/grading-report.md
mkdir -p "$R" "$ROOT/docs"

cp "$D/cua-agentos.iso" "$R/"
# The kernel, initramfs and base are the exact files ISOLINUX/xorriso packed into run1.iso (== cua-agentos.iso).
(cd "$D/run1" && sha256sum vmlinuz initramfs rootfs.squashfs) >"$R/SHA256SUMS"
(cd "$R" && sha256sum cua-agentos.iso) >>"$R/SHA256SUMS"

ISO=$R/cua-agentos.iso "$ROOT/tests/gate-08.sh"

EV=$(jq -cR 'fromjson? | objects | select((.ts_ms|type)=="number" and (.event|type)=="string")' "$ROOT/build/gate-08-serial.log")
ev() { printf '%s\n' "$EV" | jq -r -s "$1"; }

{
	cat <<EOF
# CUA-AgentOS grading report (Cycle 08)

Generated by \`scripts/release-08.sh\`. Every value below is taken from the ttyS0 JSON telemetry of the
\`tests/gate-08.sh\` boot of \`release/cua-agentos.iso\` (QEMU/KVM, \`-cdrom\` only, \`-m 1024 -snapshot -nic none\`),
or from that gate's exit codes. Score: **$(jq -s 'map(select(.event=="RUBRIC_PASS").weight) | add' "$ROOT/build/gate-08-rubric.jsonl")/100**.

## Rubric

| Category | Weight | Result |
|---|---|---|
EOF
	jq -r '"| \(.item) | \(.weight)% | \(.event) |"' "$ROOT/build/gate-08-rubric.jsonl"
	cat <<'EOF'

## Machine evidence

EOF
	echo '### Kernel handoff (20%)'
	echo
	echo 'The ISOLINUX boot line hands the kernel `rdinit=/usr/bin/agent-init`, so the kernel execs agent-init from the'
	echo 'initramfs as PID 1. agent-init execs `/stage1` (a busybox script) to mount the CD, the SquashFS base and the'
	echo 'OverlayFS root, which `switch_root`s back into `/usr/bin/agent-init` on the real root, still as PID 1. `/proc/cmdline`:'
	echo
	ev '"```\n" + (first(.[] | select(.event=="PID1_READY")).cmdline) + "\n```"'
	echo
	echo '### Bare-metal PID 1 (20%)'
	echo
	ev '"```json\n" + (first(.[] | select(.event=="PID1_READY")) | tojson) + "\n```"'
	echo
	echo '### Perception and 3-tier interaction (25%)'
	echo
	ev '"```json\n" + (map(select((.event | test("^TIER[123]_PASS$|^CAPABILITY_VERIFIED$")) or (.event=="INTERACTION_CYCLE_VERIFIED" and .primitive=="screencopy"))) | map(tojson) | join("\n")) + "\n```"'
	echo
	echo '### Application lifecycle (25%)'
	echo
	ev '"```json\n" + (map(select((.event | test("^STORAGE_READY$|^LIFECYCLE_|^CAPABILITY_INSTALLED$|^CAPABILITY_ROLLBACK$|^ROLLBACK_"))
		or (.event=="TASK_COMPLETE" and .task_id=="t06-lifecycle"))) | map(tojson) | join("\n")) + "\n```"'
	echo
	echo '### Immutable build artifact (10%)'
	echo
	echo '`scripts/build-iso-07.sh` builds the image twice from scratch (`SOURCE_DATE_EPOCH=1700000000`). The gate checks'
	echo '`run1.iso` == `run2.iso` == the booted ISO by sha256 and boots with `-cdrom` only (no `-kernel`/`-initrd`):'
	echo
	echo '```'
	(cd "$D" && sha256sum run1.iso run2.iso) && sha256sum <"$R/cua-agentos.iso" | sed 's|-$|release/cua-agentos.iso|'
	echo '```'
	echo
	echo 'The `BOOT_IMAGE=/boot/vmlinuz` and `initrd=/boot/initramfs` cmdline entries above were set by ISOLINUX on the ISO. QEMU exited 0 through agent-init'"'"'s `RB_POWER_OFF` path.'
	echo
	echo '## Latency benchmarks'
	echo
	echo '| Measurement | Value | Budget |'
	echo '|---|---|---|'
	ev '(first(.[] | select(.event=="PID1_READY")).ts_ms) as $p | (first(.[] | select(.event=="AGENTD_READY")).ts_ms) as $a
		| "| Kernel start → PID1_READY | \($p) ms | ≤1000 ms |",
		  "| PID1_READY → AGENTD_READY | \($a - $p) ms | ≤3000 ms |",
		  (.[] | select(.event | test("^TIER[123]_PASS$")) | "| \(.event | sub("_PASS"; "")) \(.primitive) | \(.latency_ms) ms | ≤\(.budget_ms) ms |"),
		  (.[] | select(.event=="INTERACTION_CYCLE_VERIFIED" and .primitive=="screencopy") | "| Tier 3 screencopy (grim, \(.frames) frames) | \(.fps) FPS | ≥10 FPS |"),
		  (.[] | select(.event=="LIFECYCLE_VERIFIED" and .status=="ok") | "| Capability install verify (\(.package)) | \(.latency_ms) ms | 30 s cap |"),
		  "| Kernel start → last event | \(last(.[]).ts_ms) ms | gate 300 s |"'
	echo
	echo '## SHA-256 checksums (`release/SHA256SUMS`)'
	echo
	echo '```'
	cat "$R/SHA256SUMS"
	echo '```'
} >"$REPORT"
cp "$REPORT" "$R/grading-report.md"
echo "release: $R (report: $REPORT)"
